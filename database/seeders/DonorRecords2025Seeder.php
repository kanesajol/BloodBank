    private function donatedOn(string $mbdDate): string
    {
        if (preg_match('/(\d{1,2})\/(\d{1,2})\/(\d{4})/', $mbdDate, $match)) {
            return sprintf('%04d-%02d-%02d', (int) $match[3], (int) $match[1], (int) $match[2]);
        }

        return '2025-01-01';
    }

    private function venue(string $mbdDate): string
    {
        if (preg_match('/\b(W\.?\s*I\.?|WALK[\s-]*IN)\b/i', $mbdDate)) {
            return 'WI';
        }

        return '';
    }

    /**
     * @return array{0: string, 1: string, 2: ?string}
     */
    private function addressParts(?string $address): array
    {
        $parts = array_values(array_filter(array_map('trim', explode(',', (string) $address)), fn (string $part) => $part !== ''));

        return [
            $parts[0] ?? '',
            $parts[1] ?? '',
            $parts[2] ?? null,
        ];
    }

    private function bloodType(?string $type): ?string
    {
        if ($type === null || trim($type) === '') {
            return null;
        }

        $compact = strtoupper(str_replace([' ', '[', '.'], '', $type));
        $compact = str_replace('0', 'O', $compact);

        return match ($compact) {
            'APOS', 'APOSITIVE', 'APO', 'A+' => 'A+',
            'ANEG', 'ANEGATIVE', 'A-' => 'A-',
            'BPOS', 'BPOSITIVE', 'BPODS', 'B+' => 'B+',
            'BNEG', 'BNEGATIVE', 'B-' => 'B-',
            'OPOS', 'OPOSITIVE', 'O+' => 'O+',
            'ONEG', 'ONEGATIVE', 'O-' => 'O-',
            'ABPOS', 'ABPOSITIVE', 'ABPO', 'AB+' => 'AB+',
            'ABNEG', 'ABNEGATIVE', 'AB-' => 'AB-',
            'A', 'B', 'O', 'AB' => $compact,
            'POS' => null,
            default => mb_substr(trim($type), 0, 8),
        };
    }
}
