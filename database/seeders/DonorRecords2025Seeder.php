    /**
     * Keep Jr., Sr., II, III, and IV in the suffix field so the visible name is LAST, FIRST MIDDLE SUFFIX.
     *
     * @param  array<string, mixed>  $record
     * @return array<string, mixed>
     */
    private function withSuffix(array $record): array
    {
        $suffix = trim((string) ($record['suffix'] ?? ''));
        if (strcasecmp($suffix, 'None') === 0) {
            $suffix = '';
        }

        foreach (['last_name', 'first_name', 'middle_name'] as $field) {
            $value = trim((string) ($record[$field] ?? ''));
            if ($value === '') {
                continue;
            }

            if (preg_match('/^(JR\.?|SR\.?|III|II|IV)\.?$/iu', $value, $only) === 1) {
                $token = $this->suffixToken($only[1]);
                if ($token !== null && $field !== 'last_name' && ($suffix === '' || strcasecmp($suffix, $token) === 0)) {
                    $record[$field] = null;
                    $suffix = $suffix === '' ? $token : $suffix;
                }

                continue;
            }

            if (preg_match('/^(.*?)\s+(JR\.?|SR\.?|III|II|IV)\.?$/iu', $value, $match) !== 1) {
                continue;
            }

            $token = $this->suffixToken($match[2]);
            $rest = trim($match[1]);
            if ($token === null || $rest === '' || ($suffix !== '' && strcasecmp($suffix, $token) !== 0)) {
                continue;
            }

            $record[$field] = $rest;
            if ($suffix === '') {
                $suffix = $token;
            }
        }

        foreach (['first_name', 'middle_name'] as $field) {
            $value = trim((string) ($record[$field] ?? ''));
            if (preg_match('/^(.+?)\s+(JR\.?|SR\.?|III|II|IV)\.?\s+(.+)$/iu', $value, $match) !== 1) {
                continue;
            }

            $token = $this->suffixToken($match[2]);
            if ($token === null || ($suffix !== '' && strcasecmp($suffix, $token) !== 0)) {
                continue;
            }

            $record[$field] = trim($match[1]);
            $extra = trim($match[3]);
            if ($field === 'first_name' && $extra !== '') {
                $record['middle_name'] = trim($extra.' '.trim((string) ($record['middle_name'] ?? '')));
            }
            if ($suffix === '') {
                $suffix = $token;
            }
        }

        $last = trim((string) ($record['last_name'] ?? ''));
        $first = trim((string) ($record['first_name'] ?? ''));
        if ($first === '' && preg_match('/^(.+?)\s+(JR\.?|SR\.?|III|II|IV)\.?\s+(.+)$/iu', $last, $match) === 1) {
            $token = $this->suffixToken($match[2]);
            if ($token !== null && ($suffix === '' || strcasecmp($suffix, $token) === 0)) {
                $record['last_name'] = trim($match[1]);
                [$given, $middle] = $this->splitGiven(trim($match[3]), trim((string) ($record['middle_name'] ?? '')));
                $record['first_name'] = $given === '' ? null : $given;
                $record['middle_name'] = $middle === '' ? null : $middle;
                if ($suffix === '') {
                    $suffix = $token;
                }
            }
        }

        $record['suffix'] = $suffix === '' ? null : $suffix;

        return $record;
    }

    /**
     * @return array{0: string, 1: string}
     */
    private function splitGiven(string $rest, string $existingMiddle): array
    {
        if ($existingMiddle !== '') {
            return [$rest, $existingMiddle];
        }

        $tokens = array_values(array_filter(preg_split('/\s+/', trim($rest)) ?: [], fn ($token) => $token !== ''));
        if (count($tokens) <= 1) {
            $only = $tokens[0] ?? '';
            if ($only !== '' && preg_match('/^[A-Za-z]\.?$/u', $only) === 1) {
                return ['', $only];
            }

            return [$only, ''];
        }

        $middle = (string) array_pop($tokens);

        return [implode(' ', $tokens), $middle];
    }

    private function suffixToken(string $token): ?string
    {
        return match (strtoupper(rtrim(trim($token), '.'))) {
            'JR' => 'Jr.',
            'SR' => 'Sr.',
            'II' => 'II',
            'III' => 'III',
            'IV' => 'IV',
            default => null,
        };
    }

